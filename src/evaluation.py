def evaluate_rank_changes():

    results_folder = "evaluation/results/processed-ppe-results"

    for file in os.listdir(results_folder):

        if not file.endswith(".json"):
            continue

        file_path = os.path.join(results_folder, file)

        vulnerabilities = load_ppe_results(file_path)
        vulnerabilities = deduplicate_vulnerabilities(vulnerabilities)

        mean_change = calculate_mean_rank_change(vulnerabilities)

        repository = file.replace(".json", "")

        print(f"{repository}: Mean rank change = {mean_change}")

def get_cvss_priority(cvss):

    if cvss is None:
        return "Low"

    if cvss >= 9:
        return "Critical"

    elif cvss >= 7:
        return "High"

    elif cvss >= 4:
        return "Medium"

    else:
        return "Low"
    
def save_evaluation_results():

    results_folder = "evaluation/results/processed-ppe-results"
    output_file = "evaluation/results/summary.csv"

    rows = []

    for file in os.listdir(results_folder):

        if not file.endswith(".json"):
            continue

        file_path = os.path.join(results_folder, file)

        vulnerabilities = load_ppe_results(file_path)
        vulnerabilities = deduplicate_vulnerabilities(vulnerabilities)

        top_5 = calculate_top_n_overlap(vulnerabilities, 5)
        top_10 = calculate_top_n_overlap(vulnerabilities, 10)
        top_20 = calculate_top_n_overlap(vulnerabilities, 20)

        spearman = calculate_spearman(vulnerabilities)
        mean_rank_change = calculate_mean_rank_change(vulnerabilities)

        cvss_critical = 0
        cvss_high = 0
        cvss_medium = 0
        cvss_low = 0

        ppe_critical = 0
        ppe_high = 0
        ppe_medium = 0
        ppe_low = 0

        for vulnerability in vulnerabilities:

            cvss_priority = get_cvss_priority(
                vulnerability["cvss"]
            )

            ppe_priority = vulnerability["priority"]

            if cvss_priority == "Critical":
                cvss_critical += 1
            elif cvss_priority == "High":
                cvss_high += 1
            elif cvss_priority == "Medium":
                cvss_medium += 1
            else:
                cvss_low += 1

            if ppe_priority == "Critical":
                ppe_critical += 1
            elif ppe_priority == "High":
                ppe_high += 1
            elif ppe_priority == "Medium":
                ppe_medium += 1
            else:
                ppe_low += 1

        repository = file.replace(".json", "")

        rows.append([
            repository,
            len(vulnerabilities),

            top_5,
            top_10,
            top_20,

            spearman,
            mean_rank_change,

            cvss_critical,
            cvss_high,
            cvss_medium,
            cvss_low,

            ppe_critical,
            ppe_high,
            ppe_medium,
            ppe_low
        ])

    with open(output_file, "w", newline="", encoding="utf-8") as csvfile:

        writer = csv.writer(csvfile)

        writer.writerow([
            "Repository",
            "Unique CVEs",

            "Top-5 Overlap",
            "Top-10 Overlap",
            "Top-20 Overlap",

            "Spearman Correlation",
            "Mean Rank Change",

            "CVSS Critical",
            "CVSS High",
            "CVSS Medium",
            "CVSS Low",

            "PPE Critical",
            "PPE High",
            "PPE Medium",
            "PPE Low"
        ])

        writer.writerows(rows)

    print(f"Evaluation results saved to {output_file}")

def show_combined_unique_cves():

    results_folder = "evaluation/results/processed-ppe-results"

    all_cves = set()

    for file in os.listdir(results_folder):

        if not file.endswith(".json"):
            continue

        file_path = os.path.join(results_folder, file)

        vulnerabilities = load_ppe_results(file_path)

        unique_vulnerabilities = deduplicate_vulnerabilities(
            vulnerabilities
        )

        for vulnerability in unique_vulnerabilities:
            all_cves.add(vulnerability["cve"])

    print(f"Combined unique CVEs: {len(all_cves)}")

show_combined_unique_cves()

evaluate_top_n()

evaluate_spearman()

evaluate_rank_changes()

evaluate_priority_distribution()

save_evaluation_results()