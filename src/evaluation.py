"""
This script summarises the reports generated by the Patch Prioritisation Engine.

It reads every report in evaluation/results and produces a CSV file containing evaluation metrics for each repository.
"""

import csv
import os

results_folder = "evaluation/results"
summary_file = os.path.join(results_folder, "summary.csv")


def analyse_report(report_path):

    packages = 0
    vulnerabilities = 0
    critical = 0
    high = 0
    medium = 0
    low = 0
    kev = 0

    risk_scores = []

    with open(report_path, "r", encoding="utf-8") as file:

        for line in file:

            line = line.strip()

            if line.startswith("Package :"):
                packages += 1

            elif line.startswith("OSV ID"):
                vulnerabilities += 1

            elif line.startswith("KEV    : Yes"):
                kev += 1

            elif line.startswith("Risk Score :"):

                score = line.replace("Risk Score :", "").strip()

                try:
                    risk_scores.append(float(score))

                except ValueError:
                    pass

            elif line.startswith("Priority :"):

                priority = line.replace("Priority :", "").strip()

                if priority == "Critical":
                    critical += 1

                elif priority == "High":
                    high += 1

                elif priority == "Medium":
                    medium += 1

                elif priority == "Low":
                    low += 1

    average_score = 0

    if risk_scores:
        average_score = round(sum(risk_scores) / len(risk_scores), 2)

    return [
        packages,
        vulnerabilities,
        critical,
        high,
        medium,
        low,
        kev,
        average_score
    ]


def main():

    rows = []

    for file in os.listdir(results_folder):

        if not file.endswith(".txt"):
            continue

        report = os.path.join(results_folder, file)

        metrics = analyse_report(report)

        rows.append([file.replace(".txt", "")] + metrics)

    with open(summary_file, "w", newline="", encoding="utf-8") as csvfile:

        writer = csv.writer(csvfile)

        writer.writerow([
            "Repository",
            "Packages",
            "Vulnerabilities",
            "Critical",
            "High",
            "Medium",
            "Low",
            "KEV",
            "Average Risk Score"
        ])

        writer.writerows(rows)

    print(f"Summary written to {summary_file}")


if __name__ == "__main__":
    main()